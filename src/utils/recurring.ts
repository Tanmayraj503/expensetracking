import { Expense, RecurringRule, RecurrenceFrequency } from '../types';

/**
 * Adds days to a YYYY-MM-DD date string
 */
export function addDays(dateStr: string, days: number): string {
  const [year, month, day] = dateStr.split('-').map(Number);
  const date = new Date(year, month - 1, day);
  date.setDate(date.getDate() + days);
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Adds months to a YYYY-MM-DD date string, preserving day of month where possible
 */
export function addMonths(dateStr: string, months: number): string {
  const [year, month, day] = dateStr.split('-').map(Number);
  const targetDate = new Date(year, month - 1 + months, 1);
  const maxDaysInTargetMonth = new Date(targetDate.getFullYear(), targetDate.getMonth() + 1, 0).getDate();
  const targetDay = Math.min(day, maxDaysInTargetMonth);
  
  const y = targetDate.getFullYear();
  const m = String(targetDate.getMonth() + 1).padStart(2, '0');
  const d = String(targetDay).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Gets the next occurrence date for a given frequency
 */
export function getNextOccurrenceDate(currentDateStr: string, frequency: RecurrenceFrequency): string {
  switch (frequency) {
    case 'daily':
      return addDays(currentDateStr, 1);
    case 'weekly':
      return addDays(currentDateStr, 7);
    case 'monthly':
      return addMonths(currentDateStr, 1);
  }
}

/**
 * Automatically evaluates all active recurring rules up to the reference date
 * and generates any missing expense ledger entries.
 */
export function processRecurringRules(
  rules: RecurringRule[],
  existingExpenses: Expense[],
  referenceDate: string = '2026-10-29'
): {
  newExpenses: Expense[];
  generatedCount: number;
  updatedRules: RecurringRule[];
} {
  const generatedExpenses: Expense[] = [];
  const updatedRules: RecurringRule[] = [];

  for (const rule of rules) {
    if (!rule.isActive) {
      updatedRules.push(rule);
      continue;
    }

    let cursor = rule.startDate;
    const ruleEndDate = rule.endDate;
    let latestGeneratedDate = rule.lastGeneratedDate || rule.startDate;

    // Iterate through all occurrences from startDate up to referenceDate
    while (cursor <= referenceDate) {
      if (ruleEndDate && cursor > ruleEndDate) {
        break;
      }

      // Check if an expense with this rule ID on this date already exists
      const exists = existingExpenses.some(
        (e) => (e.recurringRuleId === rule.id && e.date === cursor) ||
               (e.merchant === rule.merchant && e.date === cursor && e.amount === rule.amount && e.isRecurring)
      );

      const alreadyGeneratedInThisRun = generatedExpenses.some(
        (e) => e.recurringRuleId === rule.id && e.date === cursor
      );

      if (!exists && !alreadyGeneratedInThisRun) {
        generatedExpenses.push({
          id: `rec-${rule.id}-${cursor}-${Math.random().toString(36).substr(2, 4)}`,
          amount: rule.amount,
          date: cursor,
          time: '08:00',
          category: rule.category,
          merchant: rule.merchant,
          paymentMethod: rule.paymentMethod,
          notes: rule.notes || `Recurring ${rule.frequency}`,
          tags: rule.tags && rule.tags.length > 0 ? [...rule.tags] : undefined,
          isRecurring: true,
          recurrenceFrequency: rule.frequency,
          recurringRuleId: rule.id,
          isAutoGenerated: true,
        });
      }

      if (cursor > latestGeneratedDate) {
        latestGeneratedDate = cursor;
      }

      cursor = getNextOccurrenceDate(cursor, rule.frequency);
    }

    updatedRules.push({
      ...rule,
      lastGeneratedDate: latestGeneratedDate,
    });
  }

  return {
    newExpenses: generatedExpenses,
    generatedCount: generatedExpenses.length,
    updatedRules,
  };
}

/**
 * Calculates next upcoming repeat date from today for display in the UI
 */
export function getUpcomingDueDate(rule: RecurringRule, referenceDate: string = '2026-10-29'): string {
  let cursor = rule.startDate;
  while (cursor <= referenceDate) {
    cursor = getNextOccurrenceDate(cursor, rule.frequency);
  }
  return cursor;
}
