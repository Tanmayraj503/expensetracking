export type ExpenseCategory =
  | 'Housing'
  | 'Groceries'
  | 'Dining & Drinks'
  | 'Transportation'
  | 'Utilities'
  | 'Shopping'
  | 'Entertainment'
  | 'Health & Fitness'
  | 'Travel'
  | 'Subscriptions'
  | 'Miscellaneous';

export type PaymentMethod =
  | 'Credit Card'
  | 'Debit Card'
  | 'Cash'
  | 'Bank Transfer'
  | 'Digital Wallet';

export type RecurrenceFrequency = 'daily' | 'weekly' | 'monthly';

export interface Expense {
  id: string;
  amount: number;
  date: string; // YYYY-MM-DD
  time: string; // HH:MM
  category: ExpenseCategory;
  merchant: string;
  paymentMethod: PaymentMethod;
  notes?: string;
  tags?: string[];
  isRecurring?: boolean;
  recurrenceFrequency?: RecurrenceFrequency;
  recurringRuleId?: string;
  isAutoGenerated?: boolean;
}

export interface RecurringRule {
  id: string;
  amount: number;
  merchant: string;
  category: ExpenseCategory;
  paymentMethod: PaymentMethod;
  frequency: RecurrenceFrequency;
  startDate: string; // YYYY-MM-DD
  endDate?: string; // optional cutoff date
  tags?: string[];
  notes?: string;
  isActive: boolean;
  lastGeneratedDate?: string; // YYYY-MM-DD
  createdAt: string;
}

export interface TagSummary {
  tag: string;
  amount: number;
  count: number;
  percentage: number;
}

export interface FrequentExpensePreset {
  id: string;
  name: string; // e.g. 'Morning Coffee'
  amount: number;
  category: ExpenseCategory;
  paymentMethod: PaymentMethod;
  tags?: string[];
  notes?: string;
  iconName?: 'Coffee' | 'Utensils' | 'Bus' | 'ShoppingBag' | 'CupSoda' | 'Car' | 'Zap' | 'Tag';
}

export interface SavingsGoal {
  id: string;
  name: string;
  targetAmount: number;
  currentAmount: number;
  category: ExpenseCategory;
  targetDate?: string; // YYYY-MM-DD
  notes?: string;
  createdAt?: string;
  tag?: string; // Tag identifier used to match and accumulate savings from transactions (e.g. "Emergency Fund", "Vacation")
}

export interface BudgetSettings {
  monthlyBudget: number;
  dailyTarget: number;
  autoDailyTarget: boolean;
  currency: string;
  categoryBudgets: Partial<Record<ExpenseCategory, number>>;
  savingsGoals?: SavingsGoal[];
}

export interface DaySummary {
  date: string; // YYYY-MM-DD
  dayOfMonth: number;
  total: number;
  count: number;
  isToday: boolean;
  isPastOrToday: boolean;
  isFuture: boolean;
  isOverTarget: boolean;
}

export interface CategorySummary {
  category: ExpenseCategory;
  amount: number;
  percentage: number;
  count: number;
  budgetLimit?: number;
}

export interface MonthSummary {
  yearMonth: string; // YYYY-MM
  label: string; // e.g. "October 2026"
  totalSpent: number;
  budget: number;
  percentUsed: number;
  remaining: number;
  dailyAverage: number;
  projectedTotal: number;
  daysElapsed: number;
  daysInMonth: number;
  topCategory: CategorySummary | null;
  previousMonthSpend: number;
  changePercentVsPrevMonth: number | null;
}

export interface CategoryProjection {
  category: ExpenseCategory;
  currentSpent: number;
  projectedTotal: number;
  budgetLimit?: number;
  isOverLimit: boolean;
  varianceVsLimit: number;
}

export interface EndOfMonthProjection {
  yearMonth: string;
  currentSpend: number;
  predictedTotal: number;
  budget: number;
  daysElapsed: number;
  daysRemaining: number;
  daysInMonth: number;
  historicalDailyAverage: number;
  recent7DayRunRate: number;
  weekdayRunRate: number;
  weekendRunRate: number;
  remainingProjectedSpend: number;
  varianceVsBudget: number; // positive = over budget, negative = cushion
  variancePercent: number;
  status: 'on-track' | 'near-limit' | 'exceeding-limit';
  confidenceBand: {
    conservative: number;
    projected: number;
    high: number;
  };
  dailyAllowableToStayOnBudget: number;
  categoryProjections: CategoryProjection[];
  insightMessage: string;
}

